function escapeEngineeringText(value) {
  return value.replace(/[&<>"']/g, character => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  }[character]));
}

function renderEngineeringDiagram(paths) {
  const lanes = paths.map(({ label, nodes, links }) => {
    const flow = nodes.map(([name, detail], index) => {
      const connector = index < links.length ? `
          <div class="engineering-connector"><span>${escapeEngineeringText(links[index])}</span></div>` : "";
      return `
          <div class="engineering-node"><strong>${escapeEngineeringText(name)}</strong><span>${escapeEngineeringText(detail)}</span></div>${connector}`;
    }).join("");
    return `
      <div class="engineering-path">
        <p class="engineering-path-label">${escapeEngineeringText(label)}</p>
        <div class="engineering-flow" style="--edge-count: ${links.length}">${flow}
        </div>
      </div>`;
  }).join("");
  return `<figure class="engineering-diagram">${lanes}
    </figure>`;
}

function renderEngineeringList(entries, className) {
  const items = entries.map(([term, description]) => `
      <div><dt>${escapeEngineeringText(term)}</dt><dd>${escapeEngineeringText(description)}</dd></div>`).join("");
  return `<dl class="${className}">${items}
    </dl>`;
}

function renderEngineeringInterfaces(interfaces) {
  const rows = interfaces.map(([device, channel, data]) => `
        <tr><th scope="row">${escapeEngineeringText(device)}</th><td>${escapeEngineeringText(channel)}</td><td>${escapeEngineeringText(data)}</td></tr>`).join("");
  return `<table class="engineering-interfaces">
      <thead><tr><th scope="col">设备或端点</th><th scope="col">通信接口</th><th scope="col">信号或数据</th></tr></thead>
      <tbody>${rows}
      </tbody>
    </table>`;
}

function renderCaseEngineering(id, { inDialog = false } = {}) {
  const detail = caseEngineeringData[id];
  if (!detail) return "";

  const heading = inDialog ? "h3" : "h2";
  const { architecture, communication, modules, interfaces, key } = detail;
  const sections = [
    ["architecture", "项目整体架构图", renderEngineeringDiagram(architecture)],
    ["communication", communication.title, `
    <p class="engineering-note">${escapeEngineeringText(communication.note)}</p>
    ${renderEngineeringDiagram(communication.paths)}`],
    ["modules", "软件模块设计", renderEngineeringList(modules, "engineering-modules")],
    ["interfaces", "硬件通信接口设计", renderEngineeringInterfaces(interfaces)],
    ["key", "关键功能与技术说明", renderEngineeringList(key, "engineering-key")]
  ];
  return `<div class="case-engineering">
${sections.map(([suffix, title, body]) => {
    const sectionId = `engineering-${id.toLowerCase()}-${suffix}`;
    return `  <section class="engineering-section" aria-labelledby="${sectionId}">
    <${heading} id="${sectionId}">${escapeEngineeringText(title)}</${heading}>
    ${body.trim()}
  </section>`;
  }).join("\n")}
</div>`;
}

